export interface AuthStatus {
  mode: 'none' | 'token' | 'loopback' | 'invalid'
  subject: string
  /** Effective role of this session; the panel gates edit affordances on it. */
  role: string
  expires_at: number
  loopback: boolean
  login_available: boolean
  init_token_generated: boolean
  bootstrap_state: 'available' | 'redeemed' | 'uninitialised'
  bootstrap_path: string
  ttl_seconds: number
}

export interface LoginResult {
  access_token: string
  token_type: string
  expires_in: number
  expires_at: number
  role: string
}

/** One revoked token id. The id is opaque; the token itself is never stored or returned. */
export interface RevokedToken {
  jti: string
  expires_at: number
  expired: boolean
}

export interface RevocationList {
  /** Whole-second cut-off. Any token issued before it is refused, ids or no ids. */
  revoked_before: number
  count: number
  tokens: RevokedToken[]
}

