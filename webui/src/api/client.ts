export interface ProvidersDocument {
  document: { providers?: ProviderEntry[]; [key: string]: unknown }
  base_hash: string
  path: string
  mask: string
  unchanged_sentinel: string
  restart_required: boolean
  hint: string
}

export interface ProvidersPatch {
  base_hash: string
  /** One entry per provider; only `id` is required, other fields are merged. */
  providers: (Partial<ProviderEntry> & { id: string })[]
}

/**
 * What a probe reports. `credential_sent` is part of the contract rather than an
 * implementation detail: the whole safety story of the provider probe is that it is
 * false, and a UI that says "tested" without saying "without your key" invites the
 * opposite assumption.
 */
export interface ProbeResult {
  ok: boolean
  target: string
  status_code: number | null
  reachable?: boolean
  elapsed_ms: number
  error: string
  hint: string
  credential_sent: boolean
}

/** `state` is the part the UI translates; `hint` is the server's own wording (CLI/API). */
export interface AdapterProbeResult extends ProbeResult {
  mode: 'forward' | 'reverse'
  state: 'handshake_ok' | 'unauthorized' | 'not_onebot' | 'unreachable' | 'free' | 'in_use' | 'error'
  detail?: string
  retcode?: number | null
}

/** One candidate local port and what answered on it. */
export interface ScanEntry {
  port: number
  kind: 'onebot' | 'onebot_locked' | 'http' | 'closed'
  ok?: boolean
  account?: string
  detail?: string
  ws_url?: string
  status_code?: number | null
  hint?: string
}

export interface ScanResult {
  scanned: number
  results: ScanEntry[]
  /** Ready-to-apply adapter row for the first logged-in OneBot found. */
  suggestion: { kind: string; mode: string; ws_url: string; account_id: string } | null
}

export interface DiffResult {
  diff: string
  changed_fields: string[]
  base_hash: string
  new_hash: string
  empty: boolean
}

export interface ApplyResult {
  written: boolean
  changed_fields: string[]
  base_hash?: string
  restart_required?: boolean
  reason?: string
}

/** One MCP server as the editor sees it. `env_keys` is names only — never values. */
export interface McpServerRow {
  name: string
  description: string
  command: string[]
  timeout: number
  min_role: string
  env_keys: string[]
}

export interface McpServerDocument {
  servers: McpServerRow[]
  base_hash: string
  path: string
  roles: string[]
  status: Record<string, { tools: number; error: string }>
  restart_required: boolean
  hint: string
}

export interface McpServerPatchEntry {
  name: string
  description?: string
  command?: string[]
  /** Full replacement when present; omit it to keep whatever is on disk. */
  env?: Record<string, string>
  timeout?: number
  min_role?: string
  delete?: boolean
}

export interface McpPatch {
  base_hash: string
  servers: McpServerPatchEntry[]
}

export interface McpApplyResult {
  written: boolean
  changed_fields: string[]
  base_hash?: string
  restart_required?: boolean
  reason?: string
  /** Per-server outcome after the live reload. Empty when the runtime is not up. */
  servers?: Record<string, { tools: number; error: string }>
  note?: string
}
